const unresolvedNodes = new Set();
function translateNode(value, id) {
  return value.split(/(\([^()]*\))/g).map((part) => {
    if (part.startsWith("(") && part.endsWith(")")) {
      const marker = part.slice(1, -1);
      if (!/[\u0E00-\u0E7F]/u.test(marker)) return part;
      const english = markerText[marker];
      if (!english) throw new Error(`${id}: missing English marker translation: ${part}`);
      return `(${english})`;
    }
    const leading = part.match(/^\s*/u)?.[0] ?? "";
    const trailing = part.match(/\s*$/u)?.[0] ?? "";
    const content = part.slice(leading.length, part.length - trailing.length || undefined);
    if (!/[\u0E00-\u0E7F]/u.test(content)) return part;
    const english = staticText[content];
    if (english === undefined) {
      unresolvedNodes.add(`${id}: ${content}`);
      return part;
    }
    return `${leading}${english}${trailing}`;
  }).join("");
}

