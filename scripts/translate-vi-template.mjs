function translateSection(section, label) {
  const result = {};
  for (const [sourceKey, englishValue] of Object.entries(section)) {
    const translated = translations[englishValue];
    if (typeof translated !== "string") throw new Error(`Missing Vietnamese ${label} translation for: ${englishValue}`);
    result[sourceKey] = translated;
  }
  return result;
}

